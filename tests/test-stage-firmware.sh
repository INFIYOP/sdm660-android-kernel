#!/usr/bin/env bash
# Unit-style test for scripts/stage-firmware.sh against a fake stock tree.
# Every "firmware" file here is a few bytes of text; no real firmware is stored.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
STAGE="$HERE/scripts/stage-firmware.sh"
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
STOCK="$TMP/stock"
ADIR="$TMP/android/device/generic/sdm660"
fail=0

ok()  { echo "  ok   $*"; }
bad() { echo "  FAIL $*"; fail=1; }
mk()  { mkdir -p "$(dirname "$1")"; printf 'fake %s\n' "$2" > "$1"; }

# --- fake stock tree, laid out as docs/FIRMWARE.md describes ---------------
mk "$STOCK/firmware_mnt/image/mba.mbn"          mba
mk "$STOCK/firmware_mnt/image/modem.mdt"        modem
mk "$STOCK/firmware_mnt/image/modem.b00"        modem-b00
mk "$STOCK/firmware_mnt/image/modem.b01"        modem-b01
mk "$STOCK/firmware_mnt/image/adsp.mdt"         adsp
mk "$STOCK/firmware_mnt/image/adsp.b00"         adsp-b00
mk "$STOCK/vendor/firmware/a512_zap.mbn"        zap
mk "$STOCK/vendor/firmware/qcom/venus-4.4/venus.mdt" venus
mk "$STOCK/vendor/firmware/qcom/venus-4.4/venus.b00" venus-b00
mk "$STOCK/vendor/firmware/ath10k/WCN3990/hw1.0/firmware-5.bin" fw5
mk "$STOCK/vendor/firmware/ath10k/WCN3990/hw1.0/board-2.bin"    board2
mk "$STOCK/vendor/firmware/ath10k/WCN3990/hw1.0/wlanmdsp.mbn"   wlanmdsp
mk "$STOCK/bt_firmware/qca/crbtfw21.tlv"        crbt
mk "$STOCK/bt_firmware/qca/crnv21.bin"          crnv

echo "run: full fake tree (tulip)"
out="$(bash "$STAGE" "$STOCK" tulip "$ADIR" 2>&1)" || { echo "$out"; exit 1; }
FW="$ADIR/tulip/firmware"; MK="$FW/device.mk"; VF="$FW/vendor-firmware"

[ -f "$MK" ] && ok "device.mk written" || bad "device.mk missing"
grep -qx '# Generated by scripts/stage-firmware.sh - do not edit' "$MK" && ok "header line" || bad "bad header"
grep -q 'PRODUCT_COPY_FILES += \\' "$MK" && ok "PRODUCT_COPY_FILES block" || bad "no PRODUCT_COPY_FILES"

for f in mba.mbn modem.mdt modem.b00 modem.b01 adsp.mdt adsp.b00 a512_zap.mbn \
         qcom/venus-4.4/venus.mdt qcom/venus-4.4/venus.b00 \
         ath10k/WCN3990/hw1.0/firmware-5.bin ath10k/WCN3990/hw1.0/board-2.bin \
         ath10k/WCN3990/hw1.0/wlanmdsp.mbn qca/crbtfw21.tlv qca/crnv21.bin; do
  [ -f "$VF/$f" ] && ok "staged $f" || bad "not staged: $f"
  grep -q "device/generic/sdm660/tulip/firmware/vendor-firmware/$f:\$(TARGET_COPY_OUT_VENDOR)/firmware/$f" "$MK" \
    && ok "listed $f" || bad "not listed in device.mk: $f"
done

grep -q '^MISSING' <<<"$out" && bad "unexpected MISSING with a complete tree" || ok "no MISSING with complete tree"
grep -q 'staged 14 files' <<<"$out" && ok "14 files staged" || { echo "$out"; bad "unexpected staged count"; }

echo "run: empty tree (whyred, everything missing)"
mkdir -p "$TMP/empty"
ADIR2="$TMP/android2/device/generic/sdm660"
out2="$(bash "$STAGE" "$TMP/empty" whyred "$ADIR2" 2>&1)" || bad "script failed on empty tree"
grep -q '^MISSING' <<<"$out2" && ok "reports MISSING" || bad "no MISSING reported"
[ -f "$ADIR2/whyred/firmware/device.mk" ] && ok "empty device.mk still written" || bad "device.mk not written"
grep -q '^    device/' "$ADIR2/whyred/firmware/device.mk" && bad "empty tree produced copy entries" || ok "no copy entries for empty tree"

echo "run: invalid device name"
if bash "$STAGE" "$STOCK" potter "$ADIR" >/dev/null 2>&1; then bad "accepted an unknown device"; else ok "rejected unknown device"; fi

echo "run: firmware dir is replaced, not appended"
printf 'stale\n' > "$VF/stale.bin"
bash "$STAGE" "$STOCK" tulip "$ADIR" >/dev/null 2>&1
[ -f "$VF/stale.bin" ] && bad "stale file survived a re-run" || ok "stale files cleared on re-run"

if [ "$fail" -eq 0 ]; then echo "PASS"; exit 0; else echo "FAIL"; exit 1; fi
