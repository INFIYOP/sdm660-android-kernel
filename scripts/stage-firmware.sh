#!/usr/bin/env bash
# Stage the vendor firmware a mainline kernel asks for, taking files from YOUR stock images. Nothing is downloaded.
# usage: scripts/stage-firmware.sh <stock_root> <tulip|whyred> [android_device_dir]
#   stock_root: a directory containing the extracted stock vendor/firmware, firmware_mnt (NON-HLOS.bin contents, image/) and bt_firmware
#               (mount or unpack the images yourself; this script only searches the tree by file name)
# Writes <device_dir>/<device>/firmware/vendor-firmware/... and <device_dir>/<device>/firmware/device.mk
# Names come from the mainline DTs/drivers (docs/FIRMWARE.md). Missing files are reported, never invented.
set -euo pipefail
ROOT="${1:?stock_root}"; DEVN="${2:?tulip|whyred}"; ADIR="${3:-android/device/generic/sdm660}"
case "$DEVN" in tulip|whyred) ;; *) echo "device must be tulip or whyred"; exit 2;; esac
FW="$ADIR/$DEVN/firmware"; OUT="$FW/vendor-firmware"
rm -rf "$OUT"; mkdir -p "$OUT"
found=0; missing=0
# copy_set <dest_dir> <name-glob>...  (first directory under ROOT that holds the file wins; siblings b00.. are taken from the same dir)
copy_set () {
  local dest="$1"; shift
  local g first dir
  for g in "$@"; do
    first="$(find "$ROOT" -type f -name "$g" 2>/dev/null | sort | head -1 || true)"
    if [ -z "$first" ]; then echo "MISSING  $g"; missing=$((missing+1)); continue; fi
    dir="$(dirname "$first")"
    mkdir -p "$OUT/$dest"
    # take every file matching the glob from that directory
    find "$dir" -maxdepth 1 -type f -name "$g" -exec cp {} "$OUT/$dest/" \;
    echo "found    $g  <- $dir  -> $dest/"
    found=$((found+1))
  done
}
copy_set ""                         "mba.mbn" "modem.mdt" "modem.b[0-9][0-9]" "adsp.mdt" "adsp.b[0-9][0-9]" "a512_zap.*"
copy_set "qcom/venus-4.4"           "venus.mdt" "venus.b[0-9][0-9]"
copy_set "ath10k/WCN3990/hw1.0"     "wlanmdsp.mbn" "board-2.bin" "firmware-5.bin"
copy_set "qca"                      "crbtfw*.tlv" "crnv*.bin"
{
  echo "# Generated by scripts/stage-firmware.sh - do not edit"
  echo "PRODUCT_COPY_FILES += \\"
  ( cd "$OUT" && find . -type f | sed 's#^\./##' | sort ) | while read -r f; do
    echo "    device/generic/sdm660/$DEVN/firmware/vendor-firmware/$f:\$(TARGET_COPY_OUT_VENDOR)/firmware/$f \\"
  done
  echo
} > "$FW/device.mk"
echo "staged $(find "$OUT" -type f | wc -l) files; patterns found=$found missing=$missing"
echo "Check dmesg on the phone for the exact names the drivers request (docs/FIRMWARE.md)."
